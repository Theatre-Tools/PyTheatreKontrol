from typing import Protocol

from pytk.av.projectors.source import sourceStatus

from .projectorPower import _powerState


class ProjectorTransportDriver(Protocol):
    """Minimum interface for a projector driver to support."""

    def poweron(self) -> None: ...
    def poweroff(self) -> None: ...
    def cool(self) -> None: ...
    def get_raw_source_status(self, source_number: int) -> sourceStatus: ...
    def get_raw_power_state(self) -> _powerState: ...
    def get_raw_lamp_hours(self) -> int | float | None: ...
